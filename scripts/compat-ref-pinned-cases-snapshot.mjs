#!/usr/bin/env node

/**
 * Generate and verify the upstream snapshot behind the ref-pinned per-case ledger
 * (ADR-0007 amendment 2026-11-04).
 *
 *   node scripts/compat-ref-pinned-cases-snapshot.mjs --write    fetch upstream at the pinned ref and write the snapshot
 *   node scripts/compat-ref-pinned-cases-snapshot.mjs --verify   re-fetch and exit 1 on any drift, missing file, or unreachable API
 *
 * The snapshot records, per ledgered file at the pinned ref: the git blob SHA, every describe/it/test
 * title literal, and the text of each line the ledger cites. tests/compat-ref-pinned-cases.test.ts then
 * checks the ledger against it offline, so a stale case name or a citation that does not say what the
 * ledger claims is a red on the PR, with no network in the test run.
 *
 * `--verify` is the network half. An unreachable API is a FAILURE, never a pass.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractLines, extractTitleLiterals } from './lib/ref-pinned-cases.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const MANIFEST_PATH = resolve(ROOT, 'test/deploy-tests-manifest.knext.json');
export const SNAPSHOT_PATH = resolve(ROOT, 'test/compat-ref-pinned-cases.upstream.json');

export const SNAPSHOT_COMMENT =
  'Generated by scripts/compat-ref-pinned-cases-snapshot.mjs --write from vercel/next.js at `ref`. ' +
  'Do not edit by hand: tests/compat-ref-pinned-cases.test.ts checks the ref-pinned per-case ledger ' +
  '(the manifest $knextRefPinnedCases) against it, and --verify re-fetches upstream and fails on drift.';

/** Build the snapshot from the ledger and an injected `fetchFile(path, ref) -> {sha, source}`. */
export async function buildSnapshot(ledger, fetchFile) {
  const refs = [...new Set(ledger.map((e) => e.nextjsRef))];
  if (refs.length !== 1) {
    throw new Error(`the ledger must pin ONE ref, found: ${refs.join(', ') || 'none'}`);
  }
  const ref = refs[0];
  const files = {};
  for (const e of ledger) {
    const { sha, source } = await fetchFile(e.test, ref);
    files[e.test] = {
      blob: sha,
      literals: extractTitleLiterals(source),
      lines: extractLines(
        source,
        (e.upstream ?? []).map((c) => c.line),
      ),
    };
  }
  return { $comment: SNAPSHOT_COMMENT, ref, files };
}

/** Differences between the committed snapshot and one rebuilt from upstream. Empty means in sync. */
export function diffSnapshots(committed, rebuilt) {
  const out = [];
  if (committed?.ref !== rebuilt.ref)
    out.push(`ref: committed ${committed?.ref}, upstream build ${rebuilt.ref}`);
  const names = new Set([...Object.keys(committed?.files ?? {}), ...Object.keys(rebuilt.files)]);
  for (const f of [...names].sort()) {
    const a = committed?.files?.[f];
    const b = rebuilt.files[f];
    if (!a || !b) out.push(`${f}: present in only one of committed / upstream build`);
    else if (JSON.stringify(a) !== JSON.stringify(b))
      out.push(`${f}: committed snapshot differs from upstream at ${rebuilt.ref}`);
  }
  return out;
}

/** GitHub contents-API fetch. Throws on any non-200, so an unreachable upstream cannot pass. */
export async function fetchFromGitHub(
  path,
  ref,
  token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN,
) {
  const url = `https://api.github.com/repos/vercel/next.js/contents/${path}?ref=${encodeURIComponent(ref)}`;
  const res = await fetch(url, {
    headers: {
      accept: 'application/vnd.github+json',
      'user-agent': 'knext-compat-ref-pinned-cases',
      ...(token ? { authorization: `Bearer ${token}` } : {}),
    },
  });
  if (res.status !== 200) throw new Error(`GET ${path}@${ref} answered ${res.status}`);
  const body = await res.json();
  return { sha: body.sha, source: Buffer.from(body.content, 'base64').toString('utf8') };
}

/**
 * The `--verify` decision, with the network injected so it can be tested: rebuild from upstream and
 * compare with the committed snapshot. Any failure to rebuild (unreachable, rate-limited, a missing
 * file, an empty ledger) is `code: 1`; so is any difference. Only an exact match is `code: 0`.
 */
export async function verifySnapshot(ledger, committed, fetchFile) {
  let rebuilt;
  try {
    rebuilt = await buildSnapshot(ledger, fetchFile);
  } catch (err) {
    return { code: 1, lines: [`cannot build the upstream snapshot: ${err.message}`] };
  }
  const drift = diffSnapshots(committed, rebuilt);
  if (drift.length > 0) return { code: 1, lines: drift.map((d) => `DRIFT ${d}`) };
  return { code: 0, lines: [`snapshot matches upstream at ${rebuilt.ref}`] };
}

/**
 * The files the snapshot covers: every ref-pinned entry, plus every upstream-runtime-defect entry
 * (ADR-0007 amendment 2026-11-05), whose case names are checked against the same snapshot. A
 * defect entry cites no upstream line, so it contributes only its file and ref.
 */
export function snapshotLedger(manifest) {
  return [
    ...(manifest.$knextRefPinnedCases ?? []),
    ...(manifest.$knextUpstreamRuntimeDefects ?? []).map((e) => ({
      test: e.test,
      nextjsRef: e.nextjsRef,
      upstream: [],
    })),
  ];
}

async function main(argv) {
  const mode = argv[2];
  if (mode !== '--write' && mode !== '--verify') {
    console.error('usage: compat-ref-pinned-cases-snapshot.mjs --write | --verify');
    return 2;
  }
  const ledger = snapshotLedger(JSON.parse(readFileSync(MANIFEST_PATH, 'utf8')));
  if (mode === '--verify') {
    const verdict = await verifySnapshot(
      ledger,
      JSON.parse(readFileSync(SNAPSHOT_PATH, 'utf8')),
      fetchFromGitHub,
    );
    for (const line of verdict.lines) (verdict.code === 0 ? console.log : console.error)(line);
    return verdict.code;
  }
  let rebuilt;
  try {
    rebuilt = await buildSnapshot(ledger, fetchFromGitHub);
  } catch (err) {
    console.error(`cannot build the upstream snapshot: ${err.message}`);
    return 1;
  }
  writeFileSync(SNAPSHOT_PATH, `${JSON.stringify(rebuilt, null, 2)}\n`);
  console.log(
    `wrote ${SNAPSHOT_PATH} for ${rebuilt.ref} (${Object.keys(rebuilt.files).length} files)`,
  );
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(await main(process.argv));
}
