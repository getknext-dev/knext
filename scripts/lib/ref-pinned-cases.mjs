/**
 * The ref-pinned per-case ledger (ADR-0007 amendment 2026-11-04).
 *
 * WHY THIS EXISTS
 *   ADR-0007 section (h) put deterministic failures at FILE level, because a per-case list
 *   can hide a failing assertion and labelling a deterministic failure `flakey` misstates it.
 *   File level then costs every passing case in the file. The amendment admits a per-case
 *   entry for a deterministic failure ONLY under the bars below, and every bar is enforced
 *   HERE (and in tests/compat-ref-pinned-cases.test.ts), not left to prose.
 *
 * THE BARS (each one has a mutation proof in scripts/mutation-prove-compat-ref-pinned-cases.mjs)
 *   1. REF PIN       the entry carries the exact Next ref it was measured at, and that ref must be
 *                    the workflow default or the shipped pin. There is no `reaudited` escape: a
 *                    bump turns CI red until the entry is re-measured or removed.
 *   2. EXACT NAMES   every case is a full jest name (describe path + title). Its title and each
 *                    describe element must exist in the upstream file at that ref, using a committed
 *                    snapshot generated by scripts/compat-ref-pinned-cases-snapshot.mjs. A name that
 *                    no longer exists is a red, so an entry cannot outlive its subject.
 *   3. CITATION      upstream file (implied) + line + an anchor string that must be ON that line in
 *                    the snapshot, plus a mechanism category from a closed set and a written reason.
 *   4. EVIDENCE      run IDs, each with the cell it measured and the ref it measured at. A case may
 *                    claim only cells that have a run, and the number of cases claiming a cell must
 *                    equal the failures measured there. An unmeasured cell cannot be claimed.
 *   5. CAP           files and cases are both counted and capped.
 *
 * WHAT THE RUNNER DOES (verified against vercel/next.js v16.4.3, not assumed)
 *   test/get-test-filter.js merges `failed` and `flakey` into one `excludedCases` list; test/run-tests.js
 *   then passes jest `--testNamePattern '^(?!(?:<escaped names>)$).'`. Both lists DESELECT: the case does
 *   not run. A listed case that starts passing therefore stays SILENT at the same ref. What makes a
 *   fix visible is bar 1: the entry stops being admissible at any other ref.
 */

export const REF_SHAPE = /^v\d+\.\d+\.\d+$/;

/** The four credential cells, spelled as the workflows' KNEXT_LANE values. */
export const CELLS = ['node-turbopack', 'node-webpack', 'bun-turbopack', 'bun-webpack'];

/** Closed mechanism taxonomy. A new category is an ADR change, not a data edit. */
export const MECHANISM_CATEGORIES = [
  'vercel-cdn-header',
  'vercel-serving-model',
  'vercel-build-root',
  'expected-failure-gate',
  'harness-package-manager',
  'upstream-next-start-regression',
  'runtime-abi-gap',
];

/**
 * The cap. Measured need at v16.4.3 is 9 files / 19 cases: 9 of the 1,182 files the node x turbopack
 * run selected (0.8%), and 19 of the 76 cases inside those nine files. One file and one case of
 * headroom is allowed for a surprise at re-measure; more than that needs a reviewed ADR amendment.
 */
export const REF_PINNED_FILE_CAP = 10;
export const REF_PINNED_CASE_CAP = 20;

export const MIN_MECHANISM_CHARS = 60;

/**
 * Every workflow that runs the official harness (`NEXT_TEST_MODE: deploy`). Bar 1 reads the default
 * `NEXTJS_REF` of ALL of them: the v1.3 credential lane is the one that runs the newest ref, so a
 * bar that read only test-e2e-deploy.yml let that lane move while the entries stayed admissible.
 * tests/compat-ref-pinned-cases.test.ts scans .github/workflows so a new harness lane cannot be missed.
 */
export const HARNESS_LANE_WORKFLOWS = [
  '.github/workflows/test-e2e-deploy.yml',
  '.github/workflows/compat-credential-v1.3.yml',
  '.github/workflows/compat-vinext.yml',
];

const LANE_REF_DEFAULT =
  /NEXTJS_REF:\s*\$\{\{\s*github\.event\.inputs\.nextjsRef\s*\|\|\s*'([^']+)'\s*\}\}/;

/** The default `NEXTJS_REF` a lane workflow runs when no ref is dispatched. Throws if it cannot be read. */
export function laneDefaultRef(workflowSource, name = 'workflow') {
  const m = workflowSource.match(LANE_REF_DEFAULT);
  if (!m || !REF_SHAPE.test(m[1])) {
    throw new Error(`${name}: cannot read a vX.Y.Z default NEXTJS_REF`);
  }
  return m[1];
}

/** jest's full test name: describe path and title, joined by single spaces. */
export function caseName(c) {
  return [...(c.path ?? []), c.title].join(' ');
}

function numericRefCompare(a, b) {
  const pa = a.replace(/^v/, '').split('.').map(Number);
  const pb = b.replace(/^v/, '').split('.').map(Number);
  for (let i = 0; i < 3; i++) if (pa[i] !== pb[i]) return pa[i] - pb[i];
  return 0;
}

/** True iff `ref` is the workflow default, or the shipped pin while that pin is ahead of the default. */
export function refPinAdmissible(ref, laneRefs, shippedRef) {
  if (laneRefs.includes(ref)) return true;
  return ref === shippedRef && laneRefs.every((lane) => numericRefCompare(shippedRef, lane) > 0);
}

/** Does a source string literal (which may hold jest %s placeholders) produce this describe text? */
export function literalProduces(literal, text) {
  const escaped = literal.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/%s/g, '.+');
  return new RegExp(`^${escaped}$`).test(text);
}

const TITLE_CALL =
  /\b(?:describe|it|test)(?:\.[A-Za-z]+)*(?:\.each\(\[[^\]]*\]\))?\(\s*(['"`])((?:\\.|(?!\1)[^\\])*)\1/g;

/** Every first-argument string literal of a describe/it/test call in an upstream test source. */
export function extractTitleLiterals(source) {
  const out = new Set();
  for (const m of source.matchAll(TITLE_CALL)) out.add(m[2].replace(/\\(['"`\\])/g, '$1'));
  return [...out].sort();
}

/** The text of the 1-indexed lines asked for, keyed by line number. */
export function extractLines(source, lineNumbers) {
  const all = source.split('\n');
  const out = {};
  for (const n of lineNumbers) out[String(n)] = all[n - 1] ?? '';
  return out;
}

const PROVENANCE_URL = /^https:\/\/github\.com\/[\w.-]+\/[\w.-]+\/(issues|pull)\/\d+/;

/**
 * Validate the ledger against everything that can be checked offline.
 *
 * @param {object} p
 * @param {Array}  p.ledger                the `$knextRefPinnedCases` array
 * @param {object} p.suites                the manifest `suites` map
 * @param {string[]} p.rulesExclude        the manifest `rules.exclude`
 * @param {object} p.snapshot              parsed test/compat-ref-pinned-cases.upstream.json
 * @param {string[]} p.laneRefs            the default NEXTJS_REF of EVERY workflow that runs the harness
 *                                         (test-e2e-deploy.yml, compat-credential-v1.3.yml, compat-vinext.yml)
 * @param {string} p.shippedRef            .github/compat-credentialed-next-version.json shipped pin, as vX.Y.Z
 * @param {Set<string>} p.upstreamMirror   suites files that are verbatim upstream mirrors
 * @returns {string[]} error messages; empty means admissible
 */
export function validateRefPinnedCases({
  ledger,
  suites,
  rulesExclude,
  snapshot,
  laneRefs,
  shippedRef,
  upstreamMirror,
}) {
  const errs = [];
  const entries = Array.isArray(ledger) ? ledger : [];
  if (!Array.isArray(ledger)) errs.push('$knextRefPinnedCases must be an array');

  const seenFiles = new Set();
  let caseTotal = 0;
  const ledgerFiles = new Set();

  for (const e of entries) {
    const where = `${e?.test ?? '<no test>'}`;
    if (typeof e?.test !== 'string' || !/^test\/.+\.test\.(t|j)sx?$/.test(e.test)) {
      errs.push(`${where}: "test" must be an upstream test file path`);
      continue;
    }
    if (seenFiles.has(e.test)) errs.push(`${where}: two ledger entries for one file`);
    seenFiles.add(e.test);
    ledgerFiles.add(e.test);

    // Bar 1: the ref pin.
    if (typeof e.nextjsRef !== 'string' || !REF_SHAPE.test(e.nextjsRef)) {
      errs.push(`${where}: nextjsRef must be vX.Y.Z`);
    } else if (!refPinAdmissible(e.nextjsRef, laneRefs, shippedRef)) {
      errs.push(
        `${where}: pinned at ${e.nextjsRef} but no lane runs it (lane defaults: ${laneRefs.join(', ')}) and the shipped pin is ${shippedRef}. ` +
          'A ref-pinned entry stops being admissible at any other ref: re-measure it at the new ref or remove it.',
      );
    }
    if ('reaudited' in e) {
      errs.push(
        `${where}: a ref-pinned entry cannot be "reaudited" by source equivalence; re-measure it`,
      );
    }

    // Bar 3: category, reason, provenance, retirement.
    if (!MECHANISM_CATEGORIES.includes(e.mechanismCategory)) {
      errs.push(`${where}: mechanismCategory "${e.mechanismCategory}" is not in the closed set`);
    }
    if (typeof e.mechanism !== 'string' || e.mechanism.trim().length < MIN_MECHANISM_CHARS) {
      errs.push(
        `${where}: mechanism must be a written reason of at least ${MIN_MECHANISM_CHARS} characters`,
      );
    }
    if (typeof e.provenance !== 'string' || !PROVENANCE_URL.test(e.provenance)) {
      errs.push(`${where}: provenance must link a GitHub issue or pull request`);
    }
    if (typeof e.retire !== 'string' || e.retire.trim().length < 20) {
      errs.push(`${where}: retire must state when the entry goes away`);
    }

    // Bar 4: evidence. Runs, then the cells the cases may claim.
    const runs = Array.isArray(e.runs) ? e.runs : [];
    if (runs.length === 0) errs.push(`${where}: no runs cited`);
    const measuredCells = new Set();
    for (const r of runs) {
      if (!/^\d{8,}$/.test(String(r?.run ?? '')))
        errs.push(`${where}: run id "${r?.run}" is not a run id`);
      if (!CELLS.includes(r?.cell))
        errs.push(`${where}: run ${r?.run} names unknown cell "${r?.cell}"`);
      else measuredCells.add(r.cell);
      if (r?.ref !== e.nextjsRef) {
        errs.push(`${where}: run ${r?.run} measured ${r?.ref}, not the pinned ${e.nextjsRef}`);
      }
    }
    const measured = e.measured && typeof e.measured === 'object' ? e.measured : {};
    for (const cell of Object.keys(measured)) {
      if (!measuredCells.has(cell)) errs.push(`${where}: measured counts for ${cell} have no run`);
    }
    for (const cell of measuredCells) {
      const m = measured[cell];
      if (!m || !Number.isInteger(m.failed) || m.failed < 0) {
        errs.push(`${where}: cell ${cell} has a run but no measured failed count`);
      }
    }

    // Bar 2: exact names.
    const cases = Array.isArray(e.cases) ? e.cases : [];
    if (cases.length === 0) errs.push(`${where}: no cases`);
    caseTotal += cases.length;
    const names = new Set();
    const claimed = {};
    for (const c of cases) {
      const hasPath =
        Array.isArray(c?.path) && c.path.every((p) => typeof p === 'string' && p.trim());
      if (!hasPath || typeof c?.title !== 'string' || !c.title.trim()) {
        errs.push(`${where}: a case needs a describe path and a title`);
        continue;
      }
      const name = caseName(c);
      if (names.has(name)) errs.push(`${where}: duplicate case "${name}"`);
      names.add(name);
      const cells = Array.isArray(c.cells) ? c.cells : [];
      if (cells.length === 0) errs.push(`${where}: case "${name}" claims no cell`);
      for (const cell of cells) {
        if (!measuredCells.has(cell)) {
          errs.push(`${where}: case "${name}" claims cell ${cell}, which has no measured run`);
        }
        claimed[cell] = (claimed[cell] ?? 0) + 1;
      }
    }
    for (const cell of measuredCells) {
      const m = measured[cell];
      if (m && Number.isInteger(m.failed) && (claimed[cell] ?? 0) !== m.failed) {
        errs.push(
          `${where}: cell ${cell} measured ${m.failed} failure(s) but ${claimed[cell] ?? 0} case(s) claim it`,
        );
      }
    }

    // Bars 2 and 3 against the committed upstream snapshot.
    const snap = snapshot?.files?.[e.test];
    if (!snap) {
      errs.push(`${where}: no upstream snapshot for this file`);
    } else {
      if (snapshot.ref !== e.nextjsRef) {
        errs.push(`${where}: snapshot is for ${snapshot.ref}, entry is pinned at ${e.nextjsRef}`);
      }
      const literals = snap.literals ?? [];
      for (const c of cases) {
        if (typeof c?.title !== 'string') continue;
        const name = caseName(c);
        if (!literals.some((l) => literalProduces(l, c.title))) {
          errs.push(
            `${where}: case "${name}" no longer exists upstream at ${e.nextjsRef} (title not found)`,
          );
        }
        for (const p of c.path ?? []) {
          if (!literals.some((l) => literalProduces(l, p))) {
            errs.push(
              `${where}: case "${name}" no longer exists upstream at ${e.nextjsRef} (describe "${p}" not found)`,
            );
          }
        }
      }
      const cites = Array.isArray(e.upstream) ? e.upstream : [];
      if (cites.length === 0) errs.push(`${where}: no upstream citation (file line + anchor)`);
      for (const cite of cites) {
        if (!Number.isInteger(cite?.line) || cite.line < 1 || !cite?.anchor) {
          errs.push(`${where}: a citation needs an integer line and an anchor`);
          continue;
        }
        const text = snap.lines?.[String(cite.line)];
        if (typeof text !== 'string') {
          errs.push(`${where}: cited line ${cite.line} is not in the upstream snapshot`);
        } else if (!text.includes(cite.anchor)) {
          errs.push(
            `${where}: line ${cite.line} at ${e.nextjsRef} does not contain "${cite.anchor}"`,
          );
        }
      }
    }

    // The runner-facing list: suites[file].failed must be exactly these names.
    const failed = suites?.[e.test]?.failed ?? [];
    const want = cases.filter((c) => c?.title).map(caseName);
    for (const n of want) {
      if (!failed.includes(n))
        errs.push(`${where}: "${n}" is in the ledger but not in suites.failed`);
    }
    for (const n of failed) {
      if (!want.includes(n))
        errs.push(`${where}: suites.failed has "${n}", which the ledger does not record`);
    }
    if (rulesExclude?.includes(e.test)) {
      errs.push(`${where}: a per-case entry must not also be file-level excluded`);
    }
  }

  // No unledgered `failed` list outside the verbatim upstream mirror.
  for (const [file, s] of Object.entries(suites ?? {})) {
    if (upstreamMirror?.has(file)) continue;
    if ((s.failed ?? []).length > 0 && !ledgerFiles.has(file)) {
      errs.push(
        `suites["${file}"].failed has no $knextRefPinnedCases record: an unledgered per-case list is forbidden`,
      );
    }
  }

  // Bar 5: the cap.
  if (seenFiles.size > REF_PINNED_FILE_CAP) {
    errs.push(
      `${seenFiles.size} files exceed the cap of ${REF_PINNED_FILE_CAP}; a higher cap needs an ADR-0007 amendment`,
    );
  }
  if (caseTotal > REF_PINNED_CASE_CAP) {
    errs.push(
      `${caseTotal} cases exceed the cap of ${REF_PINNED_CASE_CAP}; a higher cap needs an ADR-0007 amendment`,
    );
  }
  return errs;
}

/** Passing cases a cell stops running because of this ledger, from the measured counts. */
export function passingCasesLostPerCell(ledger) {
  const lost = Object.fromEntries(CELLS.map((c) => [c, 0]));
  for (const e of ledger) {
    for (const cell of Object.keys(e.measured ?? {})) {
      for (const c of e.cases) if (!c.cells.includes(cell)) lost[cell] += 1;
    }
  }
  return lost;
}
