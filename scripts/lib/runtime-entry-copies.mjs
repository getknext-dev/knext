/**
 * Strip the sanctioned generated-by header, and ONLY that.
 *
 * @param {string} source
 * @returns {string}
 */
export function stripGeneratedByHeader(source) {
  if (!source.startsWith('/**')) return source;
  const end = source.indexOf('*/');
  if (end === -1) return source;
  const header = source.slice(0, end + 2);
  if (!header.includes(GENERATED_BY_MARKER)) return source;
  return source.slice(end + 2).replace(/^\r?\n/, '');
}

/**
 * Every copy of a `COPY_BASENAMES` file in the tree, as repo-relative POSIX
 * paths, sorted. `.hbs` variants count: a template IS a copy.
 *
 * @param {string} repoRoot
 * @returns {string[]}
 */
export function discoverRuntimeEntryCopies(repoRoot) {
  const root = resolve(repoRoot);
  const found = [];
  const walk = (dir) => {
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (SKIP_DIRS.has(entry.name)) continue;
        walk(full);
        continue;
      }
      if (!entry.isFile()) continue;
      const base = entry.name.replace(/\.hbs$/, '');
      if (!COPY_BASENAMES.includes(base)) continue;
      found.push(relative(root, full).split(sep).join('/'));
    }
  };
  walk(root);
  return found.sort();
}

/** @param {string} text */
export function sha256(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex');
}

/**
 * Compare every discovered copy against its canonical template.
 *
 * @param {{ repoRoot: string }} opts
 * @returns {string[]} one finding per violation, `[]` when the tree is clean
 */
export function auditRuntimeEntryCopies({ repoRoot }) {
  const root = resolve(repoRoot);
  const findings = [];
  const copies = discoverRuntimeEntryCopies(root);

  /** @type {Map<string, string>} */
  const canonical = new Map();
  for (const rel of CANONICAL_TEMPLATES) {
    const base = rel
      .split('/')
      .pop()
      .replace(/\.hbs$/, '');
    let src;
    try {
      src = readFileSync(join(root, rel), 'utf8');
    } catch {
      findings.push(`canonical template ${rel} is missing — there is nothing to pin the copies to`);
      continue;
    }
    if (!src.includes(GENERATED_BY_MARKER)) {
      findings.push(
        `${rel} no longer carries the generated-by header (${JSON.stringify(GENERATED_BY_MARKER)}) — ` +
          'the header strip would silently become a no-op',
      );
    }
    canonical.set(base, stripGeneratedByHeader(src));
  }

  // A walker that finds nothing passes vacuously, so the walk is asserted too:
  // both canonical templates must be among the DISCOVERED set, not merely
  // readable by path. Driven by the LITERAL path list, so neutering the
  // basename matcher the walk uses reds here instead of going quiet.
  for (const rel of CANONICAL_TEMPLATES) {
    if (!copies.includes(rel)) {
      findings.push(`the scan did not discover ${rel} — discovery is broken, not the tree`);
    }
  }

  for (const rel of copies) {
    const base = rel
      .split('/')
      .pop()
      .replace(/\.hbs$/, '');
    const expected = canonical.get(base);
    if (expected === undefined) continue;
    if (rel === `${CANONICAL_TEMPLATE_DIR}/${base}.hbs`) continue;

    const actual = readFileSync(join(root, rel), 'utf8');
    const recorded = DIVERGENT[rel];
    if (recorded) {
      const got = sha256(actual);
      if (got !== recorded.sha256) {
        findings.push(
          `${rel} is a RECORDED divergence whose bytes changed (sha256 ${got}, recorded ` +
            `${recorded.sha256}). Reconcile it into the template, or update the hash together ` +
            'with the reason in scripts/lib/runtime-entry-copies.mjs.',
        );
      }
      continue;
    }
    if (stripGeneratedByHeader(actual) !== expected) {
      findings.push(
        `${rel} differs from ${CANONICAL_TEMPLATE_DIR}/${base}.hbs by more than the sanctioned ` +
          'generated-by header. One file, five homes: reconcile the change into the template ' +
          'and re-copy, or record the divergence with a reason and a hash.',
      );
    }
  }

  // A stale exemption is a hole that outlives its subject.
  for (const rel of Object.keys(DIVERGENT)) {
    if (!copies.includes(rel)) {
      findings.push(
        `${rel} is recorded as a divergence but no longer exists — delete the DIVERGENT entry`,
      );
    }
  }

  return findings;
}
