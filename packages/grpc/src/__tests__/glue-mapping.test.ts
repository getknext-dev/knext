/**
 * The RPC -> Next.js shape mapping of the generated glue, one test per row:
 *
 *   | RPC                                   | generated as                                   |
 *   |---------------------------------------|------------------------------------------------|
 *   | unary, NO_SIDE_EFFECTS, AUTH_USER     | server-only query: authorize, then 'use cache' |
 *   | unary, NO_SIDE_EFFECTS, AUTH_PUBLIC   | server-only query, no authorize, public key    |
 *   | any other unary (AUTH_USER)           | 'use server' action, then updateTag            |
 *   | server-streaming                      | server-only async generator, never an action   |
 *
 * The assertions read the generated TypeScript as a syntax tree (not as text),
 * so they pin structure: which function holds the 'use cache' directive, what
 * its parameters are, and which calls happen inside it and which outside.
 */

import { describe, expect, it } from 'bun:test';
import ts from 'typescript';
import { generateFiles } from '../generate';
import { FIXTURE_ZONE } from './helpers';

const files = generateFiles(FIXTURE_ZONE);

function parse(path: string): ts.SourceFile {
  const text = files.get(path);
  if (text === undefined)
    throw new Error(`not generated: ${path}\n${[...files.keys()].join('\n')}`);
  return ts.createSourceFile(path, text, ts.ScriptTarget.ES2022, true, ts.ScriptKind.TS);
}

const SERVER = 'orders/v1/orders_knext_server.ts';
const ACTIONS = 'orders/v1/orders_knext_actions.ts';
const CATALOG_SERVER = 'orders/v1/catalog_knext_server.ts';
const CATALOG_ACTIONS = 'orders/v1/catalog_knext_actions.ts';

function directives(body: ts.Block | ts.SourceFile): string[] {
  const out: string[] = [];
  for (const st of body.statements) {
    if (ts.isExpressionStatement(st) && ts.isStringLiteral(st.expression)) {
      out.push(st.expression.text);
    } else break;
  }
  return out;
}

function functionNamed(sf: ts.SourceFile, name: string): ts.FunctionDeclaration {
  const fn = sf.statements.find(
    (s): s is ts.FunctionDeclaration => ts.isFunctionDeclaration(s) && s.name?.text === name,
  );
  if (!fn?.body) throw new Error(`no function ${name} in ${sf.fileName}`);
  return fn;
}

function isExported(fn: ts.FunctionDeclaration): boolean {
  return fn.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword) ?? false;
}

function isAsync(fn: ts.FunctionDeclaration): boolean {
  return fn.modifiers?.some((m) => m.kind === ts.SyntaxKind.AsyncKeyword) ?? false;
}

/** Every called name in `node`, in source order (`a.b(...)` -> `b`, `$c()` -> `c`). */
function calls(node: ts.Node): string[] {
  const out: string[] = [];
  const walk = (n: ts.Node) => {
    if (ts.isCallExpression(n)) {
      const e = n.expression;
      // The generated code imports helpers under `$` aliases ($userSubject).
      if (ts.isIdentifier(e)) out.push(e.text.replace(/^\$/, ''));
      else if (ts.isPropertyAccessExpression(e)) out.push(e.name.text);
    }
    ts.forEachChild(n, walk);
  };
  walk(node);
  return out;
}

function exportedFunctions(sf: ts.SourceFile): string[] {
  return sf.statements
    .filter((s): s is ts.FunctionDeclaration => ts.isFunctionDeclaration(s) && isExported(s))
    .map((f) => f.name?.text ?? '');
}

function importsFrom(sf: ts.SourceFile): string[] {
  return sf.statements
    .filter(ts.isImportDeclaration)
    .map((i) => (i.moduleSpecifier as ts.StringLiteral).text);
}

describe('glue mapping — every generated module is server-only', () => {
  it('each glue file imports "server-only"', () => {
    for (const path of [SERVER, ACTIONS, CATALOG_SERVER]) {
      expect(importsFrom(parse(path)), path).toContain('server-only');
    }
  });

  it('no glue file is written for a service with nothing of that shape', () => {
    // catalog.proto has one public read and no write: no actions module.
    expect(files.has(CATALOG_ACTIONS)).toBe(false);
  });

  it('the glue is generated from the contract, beside the protoc-gen-es types', () => {
    const header = files.get(SERVER) ?? '';
    expect(header).toContain('@generated by protoc-gen-knext-glue');
    expect(header).toContain('@generated from file orders/v1/orders.proto');
    expect(importsFrom(parse(SERVER))).toContain('./orders_pb');
    expect(importsFrom(parse(SERVER))).toContain('./orders_knext');
  });
});

describe('glue mapping — NO_SIDE_EFFECTS + AUTH_USER -> cached server-only query', () => {
  const sf = parse(SERVER);

  it('exports an async query for the read', () => {
    const fn = functionNamed(sf, 'getOrder');
    expect(isExported(fn)).toBe(true);
    expect(isAsync(fn)).toBe(true);
  });

  it("the query authorizes OUTSIDE the cache, then calls the 'use cache' function", () => {
    const outer = functionNamed(sf, 'getOrder');
    expect(directives(outer.body as ts.Block)).not.toContain('use cache');
    const c = calls(outer);
    expect(c).toContain('userSubject');
    expect(c).toContain('servedVersion');
    expect(c.indexOf('userSubject')).toBeLessThan(c.indexOf('getOrder$cached'));
    expect(c).not.toContain('mintCallToken');
  });

  it('the cached function keys on (subject, served version, request) and never on a token', () => {
    const cached = functionNamed(sf, 'getOrder$cached');
    expect(isExported(cached)).toBe(false);
    expect(isAsync(cached)).toBe(true);
    expect(directives(cached.body as ts.Block)).toEqual(['use cache']);
    const params = cached.parameters.map((p) => (p.name as ts.Identifier).text);
    expect(params).toEqual(['subject', 'protoVersion', 'request']);
    for (const p of params) expect(p.toLowerCase()).not.toContain('token');
  });

  it('the token is minted INSIDE the cached function, after the cache settings', () => {
    const c = calls(functionNamed(sf, 'getOrder$cached'));
    expect(c).toContain('mintCallToken');
    expect(c).toContain('cacheLife');
    expect(c).toContain('cacheTag');
    expect(c).toContain('getOrder'); // the client call
    expect(c).not.toContain('userSubject');
    expect(c).not.toContain('authorize');
    expect(c.indexOf('mintCallToken')).toBeGreaterThan(c.indexOf('cacheTag'));
  });

  it('reads are tagged with their service tag, which the writes update', () => {
    const text = files.get(SERVER) ?? '';
    expect(text).toContain('"knext:orders:orders.v1.OrdersService"');
    expect(files.get(ACTIONS) ?? '').toContain('"knext:orders:orders.v1.OrdersService"');
  });

  it('the served proto version is read from <NAME>_SERVICE_PROTO_VERSION', () => {
    expect(files.get(SERVER) ?? '').toContain('"ORDERS_SERVICE_PROTO_VERSION"');
  });
});

describe('glue mapping — NO_SIDE_EFFECTS + AUTH_PUBLIC -> query without a user', () => {
  const sf = parse(CATALOG_SERVER);

  it('does not call authorize(), and keys on the public subject', () => {
    const outer = functionNamed(sf, 'getMenu');
    expect(isExported(outer)).toBe(true);
    const c = calls(outer);
    expect(c).not.toContain('userSubject');
    expect(outer.getText()).toContain('PUBLIC_SUBJECT');
    expect(importsFrom(sf).some((m) => m.includes('authorize'))).toBe(false);
  });

  it("is still a 'use cache' function with the token minted inside", () => {
    const cached = functionNamed(sf, 'getMenu$cached');
    expect(directives(cached.body as ts.Block)).toEqual(['use cache']);
    expect(calls(cached)).toContain('mintCallToken');
  });
});

describe("glue mapping — other unary -> 'use server' action + updateTag", () => {
  const sf = parse(ACTIONS);

  it("the module is a 'use server' module whose every export is an async function", () => {
    expect(directives(sf)).toEqual(['use server']);
    for (const st of sf.statements) {
      const exported =
        ts.canHaveModifiers(st) &&
        ts.getModifiers(st)?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
      if (!exported) continue;
      expect(ts.isFunctionDeclaration(st) && isAsync(st)).toBe(true);
    }
  });

  it('exports exactly the writes: PlaceOrder and the IDEMPOTENT CancelOrder', () => {
    expect(exportedFunctions(sf).sort()).toEqual(['cancelOrder', 'placeOrder']);
  });

  it('every action runs the end-user check first, then calls, then updates the tag', () => {
    for (const name of ['placeOrder', 'cancelOrder']) {
      const c = calls(functionNamed(sf, name));
      expect(c[0], name).toBe('userSubject');
      const call = c.lastIndexOf(name);
      expect(call, name).toBeGreaterThan(c.indexOf('mintCallToken'));
      expect(c.indexOf('updateTag'), name).toBeGreaterThan(call);
    }
  });

  it('an action takes the idempotency key from its caller', () => {
    const fn = functionNamed(sf, 'placeOrder');
    expect(fn.parameters.map((p) => (p.name as ts.Identifier).text)).toEqual([
      'request',
      'options',
    ]);
    expect(fn.getText()).toContain('idempotencyKey');
  });
});

describe('glue mapping — server-streaming -> server-only generator, never an action', () => {
  const sf = parse(SERVER);

  it('exports an async generator for the stream from the server-only module', () => {
    const fn = functionNamed(sf, 'watchOrders');
    expect(isExported(fn)).toBe(true);
    expect(fn.asteriskToken).toBeDefined();
    expect(directives(fn.body as ts.Block)).toEqual([]);
    const c = calls(fn);
    expect(c[0]).toBe('userSubject');
    expect(c).toContain('mintCallToken');
  });

  it('the stream is not in the actions module and is never cached', () => {
    expect(exportedFunctions(parse(ACTIONS))).not.toContain('watchOrders');
    expect(() => functionNamed(sf, 'watchOrders$cached')).toThrow();
  });
});
